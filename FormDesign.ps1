# Form designs as JSON: a snapshot (the text Application.SaveAsText writes for each
# form, see FormSnapshot.ps1) turned into one JSON file per form that another app can
# read to rebuild the form, for example as an HTML page. Each file has the form's
# properties, its sections in order and, in each section, its controls with position
# and size in 96 dpi px (the kit's px() units), colours as #RRGGBB with the kit colour
# token they came from, text unquoted and event handlers listed apart.
#
# Like comparing, exporting needs no Access and no Windows API, so it runs anywhere
# PowerShell runs: see FormDesign.Tests.ps1.
#
# What a snapshot holds is the form as the build saved it. Code that runs when the form
# opens (moving or resizing controls, the user's palette, dark mode, hiding controls)
# is not in it, and pictures and conditional formats come through only as a hash.

. (Join-Path $PSScriptRoot 'FormSnapshot.ps1')

$script:DesignSchema = 'access-form-design/1'

# Properties stored in twips, written as px: the comparison's list and a tab control's
# fixed tab size.
$script:DesignTwips = @($SnapshotTwips) + @('TabFixedWidth', 'TabFixedHeight')

# Positions and size, lifted out of a control's properties into its own fields.
$script:DesignBox = @('Left', 'Top', 'Width', 'Height')

# Event properties ("[Event Procedure]", a macro name or "=Function()"), listed apart
# from the look of the control so a rebuild can wire them up.
function Test-DesignEvent([string]$Name) {
    $Name -match '^On[A-Z]\w*$' -or $Name -match '^(Before|After)(Update|Insert|DelConfirm|Render|Layout|Final)\w*$'
}

# Reads the build palette's colour constants (an app's modTheme.bas, generated by
# make_themes.py) into colour number -> token name. The generator makes every build
# colour unique, so each colour in a form maps back to exactly one token; if two
# constants share a value the first one wins.
function Read-DesignTokens([string]$ThemeFile) {
    $byColour = @{}
    $tokens = [ordered]@{}
    if (-not $ThemeFile) { return [pscustomobject]@{ ByColour = $byColour; Tokens = $tokens } }
    if (-not (Test-Path -LiteralPath $ThemeFile -PathType Leaf)) { throw "No theme file at $ThemeFile." }
    foreach ($line in [IO.File]::ReadAllLines($ThemeFile)) {
        if ($line -match '^\s*Public\s+Const\s+(CLR_\w+)\s+As\s+Long\s*=\s*(-?\d+)') {
            $n = [long]$Matches[2]
            $tokens[$Matches[1]] = ConvertTo-DesignHex $n
            if (-not $byColour.ContainsKey($n)) { $byColour[$n] = $Matches[1] }
        }
    }
    [pscustomobject]@{ ByColour = $byColour; Tokens = $tokens }
}

# Access stores a colour as a BGR number (R + G*256 + B*65536).
function ConvertTo-DesignHex([long]$n) {
    '#{0:X2}{1:X2}{2:X2}' -f ($n -band 0xFF), (($n -shr 8) -band 0xFF), (($n -shr 16) -band 0xFF)
}

# One saved value as JSON-ready data: twips as px numbers, colours as { hex, token }
# (system colours, saved as negative numbers, as { system }), quoted text unquoted
# (doubled quotes undone), whole numbers as numbers. NotDefault stays as saved: it means
# the property is set to the value that isn't Access's default for it (for a yes/no
# property, the opposite of the default). Pictures and other binary values stay as the
# "<binary, n lines, hash>" text the parser leaves.
function ConvertTo-DesignValue([string]$Name, [string]$Value, $Tokens) {
    if ($Value.Length -ge 2 -and $Value.StartsWith('"') -and $Value.EndsWith('"')) {
        return $Value.Substring(1, $Value.Length - 2).Replace('""', '"')
    }
    $n = 0L
    if ([long]::TryParse($Value, [ref]$n)) {
        if ($DesignTwips -contains $Name) { return [Math]::Round($n / 15.0, 2) }
        if ($Name -match 'Color$') {
            if ($n -lt 0) { return [ordered]@{ system = $n } }
            if ($n -le 0xFFFFFF) {
                $c = [ordered]@{ hex = (ConvertTo-DesignHex $n) }
                if ($Tokens -and $Tokens.ByColour.ContainsKey($n)) { $c['token'] = $Tokens.ByColour[$n] }
                return $c
            }
        }
        return $n
    }
    $Value
}

# One parsed object (form, section or control) as a design node. Defaults are the
# form's per-type defaults ("Begin Label" blocks with no name): a control saves only
# what differs from them, so they're merged in under its own values.
function ConvertTo-DesignNode($Object, $Defaults, $Tokens, [switch]$Section) {
    $props = [ordered]@{}
    if ($Defaults) { foreach ($k in $Defaults.Keys) { $props[$k] = $Defaults[$k] } }
    foreach ($k in $Object.Props.Keys) { $props[$k] = $Object.Props[$k] }
    $node = [ordered]@{}
    $node['name'] = if ($props.Contains('Name')) { ConvertTo-DesignValue 'Name' $props['Name'] $Tokens } else { $Object.Type }
    $node['type'] = $Object.Type
    foreach ($b in $DesignBox) {
        if ($Section -and $b -ne 'Height') { continue }
        if ($props.Contains($b)) { $node[$b.ToLower()] = ConvertTo-DesignValue $b $props[$b] $Tokens }
    }
    $p = [ordered]@{}; $e = [ordered]@{}
    foreach ($k in $props.Keys) {
        if ($k -eq 'Name') { continue }
        if ($DesignBox -contains $k -and -not ($Section -and $k -ne 'Height')) { continue }
        $v = ConvertTo-DesignValue $k $props[$k] $Tokens
        if (Test-DesignEvent $k) { $e[$k] = $v } else { $p[$k] = $v }
    }
    $node['properties'] = $p
    $node['events'] = $e
    $node
}

# A parsed form (ConvertFrom-FormText) as one design: the form's own properties, then
# its sections in saved order, each with its controls. A control on a tab page or in an
# option group is listed under it as a child; its left and top are still measured from
# its section's top-left corner, as Access stores them.
function ConvertTo-FormDesign {
    param([Parameter(Mandatory)][AllowEmptyCollection()][object[]]$Objects, [Parameter(Mandatory)][string]$Name, $Tokens)
    if (-not $Objects.Count) { throw "Form $Name has no definition." }
    $root = $Objects[0]
    $defaults = @{}
    foreach ($o in $Objects) { if ($o.Key -like 'Default *') { $defaults[$o.Type] = $o.Props } }

    $design = [ordered]@{ schema = $DesignSchema; name = $Name; kind = $root.Type; units = 'px' }
    $form = ConvertTo-DesignNode $root $null $Tokens
    $design['width'] = if ($form.Contains('width')) { $form['width'] } else { $null }
    $design['properties'] = $form['properties']
    $design['events'] = $form['events']

    $nodes = @{}                       # parsed object's Key -> its node, to attach children
    $sections = New-Object System.Collections.ArrayList
    foreach ($o in $Objects) {
        if ($o.Root -or $o.Key -like 'Default *') { continue }
        if ($SnapshotSections -contains $o.Type) {
            $n = ConvertTo-DesignNode $o $null $Tokens -Section
            $n['controls'] = New-Object System.Collections.ArrayList
            [void]$sections.Add($n)
        } else {
            $n = ConvertTo-DesignNode $o $defaults[$o.Type] $Tokens
            $n['children'] = New-Object System.Collections.ArrayList
            $parent = if ($o.Parent) { $nodes[$o.Parent.Key] } else { $null }
            if ($parent -and $parent.Contains('controls')) { [void]$parent['controls'].Add($n) }
            elseif ($parent) { [void]$parent['children'].Add($n) }
            else { continue }          # outside any section: nothing Access would show
        }
        $nodes[$o.Key] = $n
    }
    $design['sections'] = $sections
    $design
}

# The design of one SaveAsText file.
function Read-FormDesign([string]$Path, $Tokens) {
    ConvertTo-FormDesign -Objects (Read-FormSnapshot $Path) -Name ([IO.Path]::GetFileNameWithoutExtension($Path)) -Tokens $Tokens
}

# Controls in a list, counting those on tab pages and in option groups.
function Measure-DesignControls($List) {
    $n = 0
    foreach ($c in $List) { $n += 1 + (Measure-DesignControls $c['children']) }
    $n
}

function Write-DesignJson([string]$Path, $Data) {
    [IO.File]::WriteAllText($Path, ($Data | ConvertTo-Json -Depth 64), (New-Object Text.UTF8Encoding($false)))
}

# Writes <form>.json for every <form>.txt in a snapshot folder, plus index.json (the
# forms written and the ones whose snapshot failed) and, with -ThemeFile, tokens.json
# (each build colour token as #RRGGBB, for CSS variables). With -Forms, only those.
# Earlier .json files in OutDir are removed first so a form the build no longer makes
# doesn't linger.
function Export-FormDesignFolder {
    param([Parameter(Mandatory)][string]$SnapshotDir, [Parameter(Mandatory)][string]$OutDir, [string]$ThemeFile, [string[]]$Forms)
    if (-not (Test-Path -LiteralPath $SnapshotDir -PathType Container)) { throw "No snapshot at $SnapshotDir." }
    $tokens = Read-DesignTokens $ThemeFile
    New-Item -ItemType Directory -Force -Path $OutDir | Out-Null
    if (-not $Forms) { Get-ChildItem -LiteralPath $OutDir -Filter *.json -File | Remove-Item }
    $files = @(Get-ChildItem -LiteralPath $SnapshotDir -Filter *.txt -File | Sort-Object BaseName)
    if ($Forms) { $files = @($files | Where-Object { $Forms -contains $_.BaseName }) }
    $written = New-Object System.Collections.ArrayList
    $failed = New-Object System.Collections.ArrayList
    foreach ($f in $files) {
        try {
            $d = Read-FormDesign $f.FullName $tokens
            Write-DesignJson (Join-Path $OutDir "$($f.BaseName).json") $d
            $count = 0
            foreach ($s in $d['sections']) { $count += Measure-DesignControls $s['controls'] }
            [void]$written.Add([ordered]@{ form = $f.BaseName; file = "$($f.BaseName).json"; sections = $d['sections'].Count; controls = $count })
        } catch {
            [void]$failed.Add([ordered]@{ form = $f.BaseName; error = $_.Exception.Message })
        }
    }
    # Forms the snapshot itself couldn't save (FormSnapshot's markers).
    foreach ($m in @(Get-ChildItem -LiteralPath $SnapshotDir -Filter *.failed -File)) {
        if (-not $Forms -or $Forms -contains $m.BaseName) { [void]$failed.Add([ordered]@{ form = $m.BaseName; error = 'snapshot failed: ' + [IO.File]::ReadAllText($m.FullName).Trim() }) }
    }
    $list = Join-Path $SnapshotDir 'unsaved-names.list'
    if (Test-Path -LiteralPath $list) {
        # ReadAllLines, not Get-Content: in Windows PowerShell 5.1 Get-Content's strings carry
        # provider note properties that ConvertTo-Json walks without end.
        foreach ($n in @([IO.File]::ReadAllLines($list, [Text.Encoding]::UTF8) | Where-Object { $_ })) {
            if (-not $Forms -or $Forms -contains $n) { [void]$failed.Add([ordered]@{ form = $n; error = "snapshot failed: the name has a character that can't be used in a file name" }) }
        }
    }
    if ($ThemeFile) { Write-DesignJson (Join-Path $OutDir 'tokens.json') ([ordered]@{ schema = $DesignSchema; theme = [IO.Path]::GetFileName($ThemeFile); tokens = $tokens.Tokens }) }
    $index = [ordered]@{
        schema = $DesignSchema
        snapshot = (Split-Path -Leaf $SnapshotDir)
        theme = $(if ($ThemeFile) { [IO.Path]::GetFileName($ThemeFile) } else { $null })
        forms = $written
        failed = $failed
    }
    Write-DesignJson (Join-Path $OutDir 'index.json') $index
    [pscustomobject]@{ Folder = $OutDir; Written = @($written | ForEach-Object { $_.form }); Failed = @($failed) }
}
